#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_caption_is_translated_and_non_empty() {
        for t in UiText::all_samples() {
            let (v, e) = (t.text(Lang::Vi), t.text(Lang::En));
            assert!(!v.trim().is_empty() && !e.trim().is_empty(), "{t:?}");
            assert_ne!(v, e, "{t:?} not translated");
            assert!(!v.contains('{') && !e.contains('{'), "{t:?}");
        }
    }

    #[test]
    fn idle_seconds_use_decimal_comma_in_vietnamese() {
        assert_eq!(UiText::IdleSecs(300).text(Lang::Vi), "0,3 giây");
        assert_eq!(UiText::IdleSecs(1000).text(Lang::Vi), "1 giây");
        assert_eq!(UiText::IdleSecs(300).text(Lang::En), "0.3 s");
    }
}
